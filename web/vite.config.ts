import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { defineConfig, type Plugin } from 'vite';

const BUILD = Date.now().toString(36);
const LABEL = new Date().toLocaleString('en-GB', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit', timeZone: 'Europe/Amsterdam' }).replace(',', '');

/**
 * Writes dist/sw.js after the build: a tiny service worker that precaches every built file,
 * so the game works offline from the iPad Home Screen. The cache name changes on every build,
 * so an update replaces the old files the next time the game is opened online.
 */
function serviceWorker(): Plugin {
  return {
    name: 'runner-sw',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = ['./', './index.html', ...Object.keys(bundle).map((f) => './' + f)]
        .concat(readdirSync('public/models').map((f) => './models/' + f)) // glTF characters (copied from public/)
        .concat(['./files.json', './manifest.webmanifest', './icons/apple-touch-icon.png', './icons/icon-192.png', './icons/icon-512.png']);
      const source = `// Generated by vite.config.ts – do not edit.
const CACHE = 'runner-${BUILD}';
const FILES = ${JSON.stringify([...new Set(files)])};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('push', (e) => {
  let d = {}; try { d = e.data ? e.data.json() : {}; } catch { d = { body: e.data && e.data.text() }; }
  e.waitUntil(Promise.all([
    self.registration.showNotification(d.title || 'Runner', { body: d.body || 'Something new is waiting!', icon: './icons/icon-192.png', badge: './icons/icon-192.png', tag: 'runner-news', data: { url: d.url || './' } }),
    self.navigator.setAppBadge ? self.navigator.setAppBadge(1).catch(() => {}) : Promise.resolve(),
  ]));
});
self.addEventListener('notificationclick', (e) => {
  e.notification.close();
  const url = new URL(e.notification.data?.url || './', self.registration.scope).href;
  e.waitUntil(self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((cs) => {
    const c = cs.find((w) => w.url.startsWith(self.registration.scope));
    return c ? c.focus().then(() => c.navigate(url)) : self.clients.openWindow(url);
  }));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  const p = new URL(e.request.url).pathname;
  if (p.endsWith('/version.json') || p.includes('/api/') || p.endsWith('/faces/index.json')) return; // always network
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) =>
    hit || fetch(e.request).catch(() => caches.match('./'))));
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
      this.emitFile({ type: 'asset', fileName: 'version.json', source: JSON.stringify({ version: BUILD, label: LABEL }) });
    },
    // files.json: hash of every public build file, so the app can fetch only what changed (src/ui/delta.ts).
    // Hashed from the bytes on disk. Never lists version.json, faces/ or support/ (private or always-network).
    closeBundle() {
      const out: Record<string, string> = {};
      const walk = (dir: string, rel = ''): void => {
        for (const n of readdirSync(dir).sort()) {
          const p = rel + n;
          if (statSync(join(dir, n)).isDirectory()) { if (n !== 'faces' && n !== 'support') walk(join(dir, n), p + '/'); continue; }
          if (p === 'version.json' || p === 'files.json') continue;
          out[p] = createHash('sha256').update(readFileSync(join(dir, n))).digest('hex').slice(0, 16);
        }
      };
      walk('dist');
      writeFileSync('dist/files.json', JSON.stringify({ version: BUILD, label: LABEL, files: out }));
    },
  };
}

export default defineConfig({
  base: './', // relative paths: works at https://<user>.github.io/<repo>/ and on localhost
  build: { target: 'es2022', chunkSizeWarningLimit: 1200 },
  define: { __APP_VERSION__: JSON.stringify(BUILD), __APP_LABEL__: JSON.stringify(LABEL) },
  plugins: [serviceWorker()],
  test: { include: ['tests/**/*.test.ts'] },
});
